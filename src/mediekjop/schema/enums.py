"""Controlled vocabularies for the unified schema.

Stored as plain strings in DuckDB (str-based enums) so values are human-readable
in the database and in exports.
"""

from __future__ import annotations

from enum import Enum


class StrEnum(str, Enum):
    """str + Enum so members compare/serialise as their value."""

    def __str__(self) -> str:  # pragma: no cover - trivial
        return self.value

    @classmethod
    def values(cls) -> list[str]:
        return [m.value for m in cls]


class Channel(StrEnum):
    META = "meta"
    SNAPCHAT = "snapchat"
    TIKTOK = "tiktok"
    YOUTUBE = "youtube"
    PINTEREST = "pinterest"


class Publisher(StrEnum):
    FACEBOOK = "facebook"
    INSTAGRAM = "instagram"
    SNAPCHAT = "snapchat"
    TIKTOK = "tiktok"
    YOUTUBE = "youtube"
    PINTEREST = "pinterest"


class CreativeFormat(StrEnum):
    STILL = "still"
    VIDEO = "video"


class Provenance(StrEnum):
    """How the creative was made. NEVER inferred from performance."""

    HUMAN_LED = "human_led"
    AI_ASSISTED = "ai_assisted"   # human concept, AI used in production
    AI_GENERATED = "ai_generated"  # concept and/or core visuals generated by AI


class HumanSubType(StrEnum):
    UGC = "ugc"
    CREATOR = "creator"
    STAFF_FOUNDER = "staff_founder"
    DOCUMENTARY = "documentary"
    STUDIO_POLISHED = "studio_polished"


class AiSubType(StrEnum):
    """What kind of AI work it is. Mirrors HumanSubType for the AI provenances."""

    PRODUCT_IMAGERY = "product_imagery"    # AI product imagery / mock-ups (ai_assisted)
    COPY_VARIANTS = "copy_variants"        # AI copy and text variants (ai_assisted)
    SYNTHETIC_UGC = "synthetic_ugc"        # synthetic people / testimonials (ai_generated)
    SYNTHETIC_SCENE = "synthetic_scene"    # AI scenes / backgrounds / visuals (ai_generated)


class Language(StrEnum):
    BOKMAL = "bokmal"
    NYNORSK = "nynorsk"
    DIALECT = "dialect"
    ENGLISH = "english"
    MIXED = "mixed"


class TagSource(StrEnum):
    """Trust hierarchy, highest trust first. UNTAGGED = provenance unknown."""

    NAMING_CONVENTION = "naming_convention"
    CSV_OVERRIDE = "csv_override"
    PLATFORM_LABEL = "platform_label"
    C2PA = "c2pa"
    UNTAGGED = "untagged"


class FunnelStage(StrEnum):
    AWARENESS = "awareness"
    CONSIDERATION = "consideration"
    CONVERSION = "conversion"


class AudienceType(StrEnum):
    PROSPECTING = "prospecting"
    LOOKALIKE = "lookalike"
    RETARGETING = "retargeting"
    BROAD = "broad"


class AgeCohort(StrEnum):
    A13_17 = "age_13_17"
    A18_24 = "age_18_24"
    A25_34 = "age_25_34"
    A35_44 = "age_35_44"
    A45_54 = "age_45_54"
    A55_PLUS = "age_55_plus"


class Gender(StrEnum):
    FEMALE = "female"
    MALE = "male"
    ALL = "all"


class RefType(StrEnum):
    """What a comment is attached to."""

    AD = "ad"
    ORGANIC = "organic"
